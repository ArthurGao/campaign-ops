#!/usr/bin/env node
// Builds the CampaignOps block for the source workflow artifact and splices it into a copy of
// the artifact HTML. Usage: node scripts/source-links.mjs [in.html] [out.html]
// Defaults: ../docs/source/workflow.html → ../docs/source/workflow.linked.html
// The block sits between the markers below; re-running replaces only that block.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const input = resolve(process.argv[2] ?? resolve(here, '../../docs/source/workflow.html'));
const output = resolve(process.argv[3] ?? resolve(here, '../../docs/source/workflow.linked.html'));

const START = '<!-- campaignops-links:start';
const END = '<!-- campaignops-links:end -->';

const map = JSON.parse(readFileSync(resolve(here, '../src/lib/source-map.json'), 'utf8'));
const css = readFileSync(resolve(here, 'source-links/block.css'), 'utf8').trim();
const js = readFileSync(resolve(here, 'source-links/block.js'), 'utf8')
  .trim()
  // Inline JSON must not close the script element.
  .replace('__CO_MAP__', () => JSON.stringify(map).replace(/</g, '\\u003c'));

const block = [
  `${START} (generated by campaign-ops/frontend/scripts/source-links.mjs from src/lib/source-map.json; edit there, not here) -->`,
  `<style id="co-links-style">\n${css}\n</style>`,
  `<script id="co-links">\n${js}\n</script>`,
  END,
].join('\n');

let html = readFileSync(input, 'utf8');
const s = html.indexOf(START);
if (s !== -1) {
  const e = html.indexOf(END, s);
  if (e === -1) throw new Error('Found the start marker without the end marker');
  html = html.slice(0, s) + block + html.slice(e + END.length);
} else {
  const body = html.lastIndexOf('</body>');
  if (body === -1) throw new Error('No </body> in the input');
  html = `${html.slice(0, body)}${block}\n${html.slice(body)}`;
}
writeFileSync(output, html);
console.log(`Wrote ${output} (${map.entries.length} map entries)`);
